const RECENT_KEY = 'smoothie_recent_icons';

export function getRecentIcons(): IconSelection[] {
	try {
		const raw = localStorage.getItem(RECENT_KEY);
		if (!raw) return [{ kind: 'emoji', value: '⚽' }];
		const parsed = JSON.parse(raw) as IconSelection[];
		return parsed.filter((i) => i.value).slice(0, 24);
	} catch {
		return [{ kind: 'emoji', value: '⚽' }];
	}
}

export function pushRecentIcon(sel: IconSelection): IconSelection[] {
	if (!sel.value || !sel.kind) return getRecentIcons();
	try {
		const current = getRecentIcons().filter((i) => !(i.kind === sel.kind && i.value === sel.value));
		const next = [sel, ...current].slice(0, 24);
		localStorage.setItem(RECENT_KEY, JSON.stringify(next));
		return next;
	} catch {
		return getRecentIcons();
	}
}

export function randomEmoji(): string {
	return ALL_EMOJIS[Math.floor(Math.random() * ALL_EMOJIS.length)];
}
